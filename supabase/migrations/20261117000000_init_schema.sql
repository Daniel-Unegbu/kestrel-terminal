-- Kestrel Terminal initial schema
-- Replaces the Drizzle migration at drizzle/migrations/0000_kestrel_dossiers_and_simulations.sql.
-- Idempotent: safe to apply to a fresh project or to the existing database.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- institutional_dossiers
-- ---------------------------------------------------------------------------
create table if not exists public.institutional_dossiers (
  id uuid primary key default gen_random_uuid(),
  entity_slug text unique not null,
  entity_name text not null,
  segment text not null,
  is_preset boolean not null default false,
  dossier_payload jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.institutional_dossiers is
  'Research dossiers generated by the research Edge Function. Publicly readable, service-role writable.';

-- Powers the "recent dossiers" strip ordered by updated_at.
create index if not exists institutional_dossiers_recent_idx
  on public.institutional_dossiers (updated_at desc)
  where is_preset = false;

alter table public.institutional_dossiers enable row level security;

-- Start from a locked-down baseline, then grant only what the browser needs.
revoke all on table public.institutional_dossiers from anon, authenticated;

grant select on table public.institutional_dossiers to anon, authenticated;
grant all on table public.institutional_dossiers to service_role;

drop policy if exists "Dossiers are publicly readable" on public.institutional_dossiers;
create policy "Dossiers are publicly readable"
  on public.institutional_dossiers
  for select
  to anon, authenticated
  using (true);

-- No INSERT/UPDATE/DELETE policy is defined on purpose: writes happen only
-- through Edge Functions using the service-role/secret key, which bypasses RLS.

-- ---------------------------------------------------------------------------
-- pilot_simulations
-- ---------------------------------------------------------------------------
create table if not exists public.pilot_simulations (
  id uuid primary key default gen_random_uuid(),
  rm_count integer not null,
  weekly_hours_saved numeric(5,1) not null,
  avg_mandate_fee_aed numeric(20,2) not null,
  win_rate_lift_pct numeric(5,2) not null,
  projected_incremental_fee_aed numeric(24,2) not null,
  created_at timestamptz not null default now(),
  constraint pilot_simulations_rm_count_positive check (rm_count > 0),
  constraint pilot_simulations_hours_non_negative check (weekly_hours_saved >= 0),
  constraint pilot_simulations_fee_non_negative check (avg_mandate_fee_aed >= 0),
  constraint pilot_simulations_lift_range check (win_rate_lift_pct >= 0 and win_rate_lift_pct <= 100)
);

comment on table public.pilot_simulations is
  'ROI simulator runs. Written by the pilot-simulation Edge Function; not exposed to anon/authenticated.';

create index if not exists pilot_simulations_created_at_idx
  on public.pilot_simulations (created_at desc);

alter table public.pilot_simulations enable row level security;

revoke all on table public.pilot_simulations from anon, authenticated;
grant all on table public.pilot_simulations to service_role;

-- Deliberately no policy for anon/authenticated. All access goes through the
-- pilot-simulation Edge Function, so the table stays closed to the public API.

-- ---------------------------------------------------------------------------
-- updated_at maintenance
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists institutional_dossiers_set_updated_at on public.institutional_dossiers;
create trigger institutional_dossiers_set_updated_at
  before update on public.institutional_dossiers
  for each row
  execute function public.set_updated_at();
